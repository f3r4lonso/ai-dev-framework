#!/usr/bin/env python3
"""Build the Codex CLI adapter from the canonical Claude Code resources.

Canonical sources (edit these, never the generated files):
  agents/<area>/<name>.md   -> clients/.codex/agents/<name>.toml  (generated, versioned)
  skills/<name>/SKILL.md    -> clients/.agents/skills/<name>      (local link, not versioned)
  agents/, skills/          -> clients/.claude/agents, skills     (local links, not versioned)
Files under agents/ without frontmatter (e.g. personal-assistants/ prompts) are not subagents and are skipped.

Commands:
  agents [--check]       Generate Codex custom-agent wrappers; --check only reports drift (exit 1).
  link-claude            Link clients/.claude/agents and clients/.claude/skills to the canonical folders,
                         so `claude --add-dir <infra>/clients` loads them.
  link-skills [--user]   Link every canonical skill into clients/.agents/skills/, or into
                         ~/.agents/skills/ with --user (for Codex sessions started in other repos).
                         Existing entries that are not links are never touched.
  status                 Show what is generated and linked.

Standard library only; no network access; writes only inside clients/.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AGENTS_SRC = ROOT / "agents"
SKILLS_SRC = ROOT / "skills"
CLIENTS = ROOT / "clients"
AGENTS_OUT = CLIENTS / ".codex" / "agents"
REPO_SKILLS_LINKS = CLIENTS / ".agents" / "skills"
CLAUDE_LINKS = CLIENTS / ".claude"
USER_SKILLS_LINKS = Path.home() / ".agents" / "skills"

HEADER = "# GENERATED by scripts/codex-adapter.py from {src}. Do not edit; edit the source and rerun.\n"
WRITE_TOOLS = {"Edit", "Write", "NotebookEdit", "Bash", "PowerShell"}


def read_frontmatter(path: Path) -> dict[str, str]:
    """Parse the flat `key: value` lines of a Markdown frontmatter block (lists are kept raw)."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path}: missing frontmatter")
    fields: dict[str, str] = {}
    key = None
    for line in lines[1:]:
        if line.strip() == "---":
            return fields
        if line[:1] in (" ", "\t") or line.startswith("-"):
            if key:
                fields[key] += " " + line.strip()
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1].replace('\\"', '"')
        fields[key] = value
    raise ValueError(f"{path}: unterminated frontmatter")


def toml_str(value: str) -> str:
    # A JSON string with ASCII escapes is a valid TOML basic string.
    return json.dumps(value, ensure_ascii=True)


def render_agent(src: Path) -> tuple[str, str]:
    fm = read_frontmatter(src)
    name, description = fm.get("name"), fm.get("description")
    if not name or not description:
        raise ValueError(f"{src}: name and description are required")
    rel = src.relative_to(ROOT).as_posix()
    tools = [t.strip() for t in fm.get("tools", "").split(",") if t.strip()]
    denied = {t.strip() for t in fm.get("disallowedTools", "").split(",") if t.strip()}
    allowed = set(tools) - denied
    read_only = bool(tools) and not allowed & WRITE_TOOLS
    no_edits = bool(tools) and not allowed & {"Edit", "Write", "NotebookEdit"}
    skills = [s for s in fm.get("skills", "").split() if s != "-"]

    instructions = [
        f"Your role definition is the canonical file `{rel}`, relative to the root of the AI infrastructure "
        "repository (two levels above this `clients/.codex/agents/` folder). Read it first and follow its "
        "body as your instructions.",
        "Its frontmatter fields `tools`, `disallowedTools`, `model`, `color` and `skills` are Claude Code "
        "settings. Treat them as follows:",
        f"- Allowed tools in Claude Code: {', '.join(tools) or 'all'}. Codex does not enforce this list; "
        "stay within it voluntarily (Read/Grep/Glob = read files and search; Bash/PowerShell = run shell "
        "commands; Edit/Write = change files; WebFetch/WebSearch = web access).",
    ]
    if read_only:
        instructions.append(
            "- This role is READ-ONLY: do not create, edit or delete files and do not run commands that "
            "change state. If the parent session is not in a read-only sandbox, this is enforced only by you."
        )
    elif no_edits:
        instructions.append(
            "- This role must NOT create or edit files (no file-editing tools in Claude Code); use the shell "
            "only to read, run tests or inspect. Codex does not enforce this; it is enforced only by you."
        )
    if skills:
        instructions.append(
            "- Preload these skills by reading their SKILL.md under `skills/<name>/` "
            f"(or invoking them as `$<name>`): {', '.join(skills)}."
        )
    instructions.append(
        "- Mentions of Claude-only features (`/agents`, `@agent-...`, CLAUDE.md, `--add-dir`) map to their "
        "Codex equivalents: custom agents, AGENTS.md and the workspace instructions in the root AGENTS.md."
    )
    body = "\n".join(instructions)
    text = (
        HEADER.format(src=rel)
        + f"name = {toml_str(name)}\n"
        + f"description = {toml_str(description)}\n"
        + f"developer_instructions = {toml_str(body)}\n"
    )
    return name, text


def agent_sources() -> list[Path]:
    """Subagent definitions: Markdown files under agents/ that start with a frontmatter block."""
    return [p for p in sorted(AGENTS_SRC.rglob("*.md"))
            if p.read_text(encoding="utf-8").startswith("---")]


def cmd_agents(check: bool) -> int:
    expected: dict[Path, str] = {}
    for src in agent_sources():
        name, text = render_agent(src)
        out = AGENTS_OUT / f"{name}.toml"
        if out in expected:
            raise ValueError(f"duplicate agent name: {name}")
        expected[out] = text
    existing = set(AGENTS_OUT.glob("*.toml")) if AGENTS_OUT.exists() else set()
    stale = sorted(p for p in existing - expected.keys()
                   if p.read_text(encoding="utf-8").startswith("# GENERATED"))
    changed = [p for p, t in expected.items()
               if not p.exists() or p.read_text(encoding="utf-8") != t]
    if check:
        for p in changed:
            print(f"out of date: {p.relative_to(ROOT).as_posix()}")
        for p in stale:
            print(f"stale: {p.relative_to(ROOT).as_posix()}")
        print(f"{len(expected)} agents, {len(changed)} out of date, {len(stale)} stale")
        return 1 if changed or stale else 0
    AGENTS_OUT.mkdir(parents=True, exist_ok=True)
    for p in changed:
        p.write_text(expected[p], encoding="utf-8", newline="\n")
    for p in stale:
        p.unlink()
    print(f"{len(expected)} agents: {len(changed)} written, {len(stale)} stale removed")
    return 0


def is_link(path: Path) -> bool:
    return path.is_symlink() or (hasattr(path, "is_junction") and path.is_junction())


def make_link(link: Path, target: Path) -> None:
    if os.name == "nt":
        # A directory junction needs no Administrator rights or Developer Mode.
        subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)],
                       check=True, stdout=subprocess.DEVNULL)
    else:
        link.symlink_to(target, target_is_directory=True)


def cmd_link_skills(user: bool) -> int:
    dest = USER_SKILLS_LINKS if user else REPO_SKILLS_LINKS
    dest.mkdir(parents=True, exist_ok=True)
    created = kept = skipped = 0
    for skill in sorted(p.parent for p in SKILLS_SRC.glob("*/SKILL.md")):
        link = dest / skill.name
        if is_link(link):
            if link.resolve() == skill.resolve():
                kept += 1
                continue
            print(f"skipped {link}: links elsewhere ({link.resolve()})")
            skipped += 1
            continue
        if link.exists():
            print(f"skipped {link}: exists and is not a link")
            skipped += 1
            continue
        make_link(link, skill)
        created += 1
    print(f"{dest}: {created} linked, {kept} already linked, {skipped} skipped")
    return 0


def cmd_link_claude() -> int:
    CLAUDE_LINKS.mkdir(parents=True, exist_ok=True)
    for name, target in (("agents", AGENTS_SRC), ("skills", SKILLS_SRC)):
        link = CLAUDE_LINKS / name
        if is_link(link):
            print(f"{link}: already linked ({link.resolve()})")
        elif link.exists():
            print(f"skipped {link}: exists and is not a link")
        else:
            make_link(link, target)
            print(f"{link}: linked to {target}")
    return 0


def cmd_status() -> int:
    agents = len(agent_sources())
    generated = len(list(AGENTS_OUT.glob("*.toml"))) if AGENTS_OUT.exists() else 0
    skills = len(list(SKILLS_SRC.glob("*/SKILL.md")))
    print(f"canonical agents: {agents}; Codex agent files: {generated}")
    print(f"canonical skills: {skills}")
    for dest in (REPO_SKILLS_LINKS, USER_SKILLS_LINKS):
        linked = sum(1 for p in dest.iterdir() if is_link(p)) if dest.exists() else 0
        print(f"links in {dest}: {linked}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p_agents = sub.add_parser("agents")
    p_agents.add_argument("--check", action="store_true")
    p_link = sub.add_parser("link-skills")
    p_link.add_argument("--user", action="store_true")
    sub.add_parser("link-claude")
    sub.add_parser("status")
    args = parser.parse_args()
    if args.command == "agents":
        return cmd_agents(args.check)
    if args.command == "link-claude":
        return cmd_link_claude()
    if args.command == "link-skills":
        return cmd_link_skills(args.user)
    return cmd_status()


if __name__ == "__main__":
    sys.exit(main())
