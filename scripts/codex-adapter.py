#!/usr/bin/env python3
"""Build the Codex CLI adapter from the canonical Claude Code resources.

Canonical sources (edit these, never the generated files):
  agents/<area>/<name>.md   -> clients/.codex/agents/<name>.toml  (generated, versioned)
  skills/<name>/SKILL.md    -> clients/.agents/skills/<name>      (local link, not versioned)
  agents/personal-assistants/<name>.md -> clients/personal/{codex,copilot,gemini}/  (generated, versioned)
Files under agents/ without frontmatter are not subagents and are skipped. Personal assistants are installed at
user level (available in every folder), so their wrappers embed the canonical body instead of pointing to it.

Commands:
  agents [--check]       Generate Codex custom-agent wrappers and the `agents` list of the Claude Code
                         plugin (.claude-plugin/plugin.json); --check only reports drift (exit 1).
  link-claude            Retired: Claude Code loads agents and skills from the `workshop` plugin
                         (.claude-plugin/); see clients/claude-code-cli/README.md.
  link-skills [--user]   Link every canonical skill into clients/.agents/skills/, or into
                         ~/.agents/skills/ with --user (for Codex sessions started in other repos).
                         Existing entries that are not links are never touched.
  personal [--check]     Generate the personal-assistant agents for Codex, Copilot CLI and Gemini CLI.
  install-personal       Copy them into ~/.codex/agents, ~/.copilot/agents and ~/.gemini/agents
                         (only files that are missing or carry the GENERATED header are written).
  status                 Show what is generated and linked.

Standard library only; no network access; writes only inside clients/ (and the user folders above with
--user or install-personal).
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AGENTS_SRC = ROOT / "agents"
SKILLS_SRC = ROOT / "skills"
CLIENTS = ROOT / "clients"
AGENTS_OUT = CLIENTS / ".codex" / "agents"
REPO_SKILLS_LINKS = CLIENTS / ".agents" / "skills"
PLUGIN_MANIFEST = ROOT / ".claude-plugin" / "plugin.json"
USER_SKILLS_LINKS = Path.home() / ".agents" / "skills"
PERSONAL_SRC = AGENTS_SRC / "personal-assistants"
PERSONAL_OUT = CLIENTS / "personal"
# client -> (generated folder, user folder the client loads, file suffix)
PERSONAL_CLIENTS = {
    "codex": (PERSONAL_OUT / "codex", Path.home() / ".codex" / "agents", ".toml"),
    "copilot": (PERSONAL_OUT / "copilot", Path.home() / ".copilot" / "agents", ".agent.md"),
    "gemini": (PERSONAL_OUT / "gemini", Path.home() / ".gemini" / "agents", ".md"),
}
COPILOT_PROMPT_LIMIT = 30000  # characters, documented limit of a Copilot agent profile body
# Claude tool -> Copilot CLI alias / Gemini CLI built-in tools
COPILOT_TOOLS = {"Read": "read", "Grep": "search", "Glob": "search", "Edit": "edit", "Write": "edit",
                 "Bash": "execute", "PowerShell": "execute", "WebFetch": "web", "WebSearch": "web"}
GEMINI_TOOLS = {"Read": ["read_file", "read_many_files"], "Grep": ["grep_search"],
                "Glob": ["glob", "list_directory"], "Edit": ["replace"], "Write": ["write_file"],
                "Bash": ["run_shell_command"], "PowerShell": ["run_shell_command"],
                "WebFetch": ["web_fetch"], "WebSearch": ["google_web_search"]}
SUBAGENT_NOTE = (
    "You run as a subagent inside a coding CLI. You cannot wait for the user mid-task: if you need "
    "clarification, return your questions (with any assumptions you would make) as your result. "
    "Stay within these tools: {tools}.{read_only}"
)

# Claude Code tools with no Copilot/Gemini equivalent: kept in the note, left out of the tool lists
CLAUDE_ONLY_TOOLS = {"Agent", "AskUserQuestion"}
MAIN_SESSION_NOTE = (
    "This role is meant to run as the main session agent, where it can ask the user questions. If you run as "
    "a subagent and cannot wait for the user, return your questions (with any assumptions you would make) "
    "as your result. Stay within these tools: {tools}."
)

HEADER = "# GENERATED by scripts/codex-adapter.py from {src}. Do not edit; edit the source and rerun.\n"
WRITE_TOOLS = {"Edit", "Write", "NotebookEdit", "Bash", "PowerShell"}


def read_frontmatter(path: Path) -> dict[str, str]:
    """Parse the flat `key: value` lines of a Markdown frontmatter block (lists are kept raw)."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path}: missing frontmatter")
    fields: dict[str, str] = {}
    key = None
    for line in lines[1:]:
        if line.strip() == "---":
            return fields
        if line[:1] in (" ", "\t") or line.startswith("-"):
            if key:
                fields[key] += " " + line.strip()
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1].replace('\\"', '"')
        fields[key] = value
    raise ValueError(f"{path}: unterminated frontmatter")


def toml_str(value: str) -> str:
    # A JSON string with ASCII escapes is a valid TOML basic string.
    return json.dumps(value, ensure_ascii=True)


def render_agent(src: Path) -> tuple[str, str]:
    fm = read_frontmatter(src)
    name, description = fm.get("name"), fm.get("description")
    if not name or not description:
        raise ValueError(f"{src}: name and description are required")
    rel = src.relative_to(ROOT).as_posix()
    tools = [t.strip() for t in fm.get("tools", "").split(",") if t.strip()]
    denied = {t.strip() for t in fm.get("disallowedTools", "").split(",") if t.strip()}
    allowed = set(tools) - denied
    read_only = bool(tools) and not allowed & WRITE_TOOLS
    no_edits = bool(tools) and not allowed & {"Edit", "Write", "NotebookEdit"}
    skills = [s for s in fm.get("skills", "").split() if s != "-"]

    instructions = [
        f"Your role definition is the canonical file `{rel}`, relative to the root of the AI infrastructure "
        "repository (two levels above this `clients/.codex/agents/` folder). Read it first and follow its "
        "body as your instructions.",
        "Its frontmatter fields `tools`, `disallowedTools`, `model`, `color` and `skills` are Claude Code "
        "settings. Treat them as follows:",
        f"- Allowed tools in Claude Code: {', '.join(tools) or 'all'}. Codex does not enforce this list; "
        "stay within it voluntarily (Read/Grep/Glob = read files and search; Bash/PowerShell = run shell "
        "commands; Edit/Write = change files; WebFetch/WebSearch = web access).",
    ]
    if read_only:
        instructions.append(
            "- This role is READ-ONLY: do not create, edit or delete files and do not run commands that "
            "change state. If the parent session is not in a read-only sandbox, this is enforced only by you."
        )
    elif no_edits:
        instructions.append(
            "- This role must NOT create or edit files (no file-editing tools in Claude Code); use the shell "
            "only to read, run tests or inspect. Codex does not enforce this; it is enforced only by you."
        )
    if skills:
        instructions.append(
            "- Preload these skills by reading their SKILL.md under `skills/<name>/` "
            f"(or invoking them as `$<name>`): {', '.join(skills)}."
        )
    instructions.append(
        "- Mentions of Claude-only features (`/agents`, `@agent-...`, CLAUDE.md, `--add-dir`) map to their "
        "Codex equivalents: custom agents, AGENTS.md and the workspace instructions in the root AGENTS.md."
    )
    body = "\n".join(instructions)
    text = (
        HEADER.format(src=rel)
        + f"name = {toml_str(name)}\n"
        + f"description = {toml_str(description)}\n"
        + f"developer_instructions = {toml_str(body)}\n"
    )
    return name, text


def agent_sources() -> list[Path]:
    """Shared subagent definitions: Markdown files under agents/ that start with a frontmatter block.
    Personal assistants are excluded; `personal` installs them at user level for every client."""
    return [p for p in sorted(AGENTS_SRC.rglob("*.md"))
            if PERSONAL_SRC not in p.parents and p.read_text(encoding="utf-8").startswith("---")]


def personal_sources() -> list[Path]:
    return [p for p in sorted(PERSONAL_SRC.glob("*.md")) if p.read_text(encoding="utf-8").startswith("---")]


def split_body(path: Path) -> str:
    """The Markdown body below the frontmatter block."""
    text = path.read_text(encoding="utf-8")
    end = text.index("\n---", 3)
    return text[end + 4:].lstrip("\n")


def yaml_list(items: list[str]) -> str:
    return "[" + ", ".join(json.dumps(i) for i in items) + "]"


def render_personal(src: Path) -> dict[str, tuple[str, str]]:
    """Return {client: (file name, text)} for one personal-assistant agent."""
    fm = read_frontmatter(src)
    name, description = fm.get("name"), fm.get("description")
    if not name or not description:
        raise ValueError(f"{src}: name and description are required")
    rel = src.relative_to(ROOT).as_posix()
    tools = [t.strip() for t in fm.get("tools", "").split(",") if t.strip()]
    unknown = [t for t in tools if t not in COPILOT_TOOLS and t not in CLAUDE_ONLY_TOOLS]
    if unknown:
        raise ValueError(f"{src}: no Copilot/Gemini mapping for tools {unknown}")
    read_only = bool(tools) and not set(tools) & WRITE_TOOLS
    note = MAIN_SESSION_NOTE.format(tools=", ".join(tools)) if "AskUserQuestion" in tools else SUBAGENT_NOTE.format(
        tools=", ".join(tools) or "all",
        read_only=" This role is READ-ONLY: never create, edit or delete files or run commands that change state."
        if read_only else "")
    header = f"GENERATED by scripts/codex-adapter.py from {rel}. Do not edit; edit the source and rerun."
    instructions = note + "\n\n" + split_body(src)
    if len(instructions) > COPILOT_PROMPT_LIMIT:
        raise ValueError(f"{src}: body exceeds the Copilot limit of {COPILOT_PROMPT_LIMIT} characters")
    copilot_tools = sorted({COPILOT_TOOLS[t] for t in tools if t in COPILOT_TOOLS})
    gemini_tools = sorted({g for t in tools if t in GEMINI_TOOLS for g in GEMINI_TOOLS[t]})
    md_head = f"name: {name}\ndescription: {json.dumps(description, ensure_ascii=False)}\n"
    return {
        "codex": (f"{name}.toml", f"# {header}\n" + f"name = {toml_str(name)}\n"
                  + f"description = {toml_str(description)}\n"
                  + f"developer_instructions = {toml_str(instructions)}\n"),
        "copilot": (f"{name}.agent.md", f"---\n{md_head}tools: {yaml_list(copilot_tools)}\n---\n\n"
                    f"<!-- {header} -->\n\n{instructions}"),
        "gemini": (f"{name}.md", f"---\n{md_head}tools: {yaml_list(gemini_tools)}\n---\n\n"
                   f"<!-- {header} -->\n\n{instructions}"),
    }


def is_generated(path: Path) -> bool:
    return "GENERATED by scripts/codex-adapter.py" in path.read_text(encoding="utf-8")[:1000]


def cmd_personal(check: bool) -> int:
    expected: dict[Path, str] = {}
    for src in personal_sources():
        for client, (file_name, text) in render_personal(src).items():
            expected[PERSONAL_CLIENTS[client][0] / file_name] = text
    existing = {p for folder, _, _ in PERSONAL_CLIENTS.values() if folder.exists() for p in folder.iterdir()}
    stale = sorted(p for p in existing - expected.keys() if p.is_file() and is_generated(p))
    changed = [p for p, t in expected.items()
               if not p.exists() or p.read_text(encoding="utf-8") != t]
    if check:
        for p in changed:
            print(f"out of date: {p.relative_to(ROOT).as_posix()}")
        for p in stale:
            print(f"stale: {p.relative_to(ROOT).as_posix()}")
        print(f"{len(expected)} personal agent files, {len(changed)} out of date, {len(stale)} stale")
        return 1 if changed or stale else 0
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(expected[p], encoding="utf-8", newline="\n")
    for p in stale:
        p.unlink()
    print(f"{len(expected)} personal agent files: {len(changed)} written, {len(stale)} stale removed")
    return 0


def cmd_install_personal() -> int:
    if cmd_personal(check=True):
        print("run `personal` first")
        return 1
    for client, (folder, dest, suffix) in PERSONAL_CLIENTS.items():
        dest.mkdir(parents=True, exist_ok=True)
        written = kept = skipped = 0
        for src in sorted(folder.glob(f"*{suffix}")):
            out = dest / src.name
            text = src.read_text(encoding="utf-8")
            if out.exists() and out.read_text(encoding="utf-8") == text:
                kept += 1
            elif out.exists() and not is_generated(out):
                print(f"skipped {out}: exists and was not generated")
                skipped += 1
            else:
                out.write_text(text, encoding="utf-8", newline="\n")
                written += 1
        print(f"{client}: {dest}: {written} written, {kept} up to date, {skipped} skipped")
    return 0


def render_plugin_manifest() -> str:
    """plugin.json with its `agents` list rebuilt: every agent file, personal assistants included."""
    manifest = json.loads(PLUGIN_MANIFEST.read_text(encoding="utf-8"))
    manifest["agents"] = ["./" + p.relative_to(ROOT).as_posix() for p in sorted(AGENTS_SRC.rglob("*.md"))
                          if p.read_text(encoding="utf-8").startswith("---")]
    return json.dumps(manifest, indent=2) + "\n"


def cmd_agents(check: bool) -> int:
    expected: dict[Path, str] = {PLUGIN_MANIFEST: render_plugin_manifest()}
    for src in agent_sources():
        name, text = render_agent(src)
        out = AGENTS_OUT / f"{name}.toml"
        if out in expected:
            raise ValueError(f"duplicate agent name: {name}")
        expected[out] = text
    existing = set(AGENTS_OUT.glob("*.toml")) if AGENTS_OUT.exists() else set()
    stale = sorted(p for p in existing - expected.keys()
                   if p.read_text(encoding="utf-8").startswith("# GENERATED"))
    changed = [p for p, t in expected.items()
               if not p.exists() or p.read_text(encoding="utf-8") != t]
    if check:
        for p in changed:
            print(f"out of date: {p.relative_to(ROOT).as_posix()}")
        for p in stale:
            print(f"stale: {p.relative_to(ROOT).as_posix()}")
        print(f"{len(expected) - 1} agents + plugin manifest, {len(changed)} out of date, {len(stale)} stale")
        return 1 if changed or stale else 0
    AGENTS_OUT.mkdir(parents=True, exist_ok=True)
    for p in changed:
        p.write_text(expected[p], encoding="utf-8", newline="\n")
    for p in stale:
        p.unlink()
    print(f"{len(expected) - 1} agents + plugin manifest: {len(changed)} written, {len(stale)} stale removed")
    return 0


def is_link(path: Path) -> bool:
    return path.is_symlink() or (hasattr(path, "is_junction") and path.is_junction())


def make_link(link: Path, target: Path) -> None:
    if os.name == "nt":
        # A directory junction needs no Administrator rights or Developer Mode.
        subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)],
                       check=True, stdout=subprocess.DEVNULL)
    else:
        link.symlink_to(target, target_is_directory=True)


def cmd_link_skills(user: bool) -> int:
    dest = USER_SKILLS_LINKS if user else REPO_SKILLS_LINKS
    dest.mkdir(parents=True, exist_ok=True)
    created = kept = skipped = 0
    for skill in sorted(p.parent for p in SKILLS_SRC.glob("*/SKILL.md")):
        link = dest / skill.name
        if is_link(link):
            if link.resolve() == skill.resolve():
                kept += 1
                continue
            print(f"skipped {link}: links elsewhere ({link.resolve()})")
            skipped += 1
            continue
        if link.exists():
            print(f"skipped {link}: exists and is not a link")
            skipped += 1
            continue
        make_link(link, skill)
        created += 1
    print(f"{dest}: {created} linked, {kept} already linked, {skipped} skipped")
    return 0


def cmd_link_claude() -> int:
    print("link-claude is retired: Claude Code loads agents and skills from the workshop plugin "
          "(.claude-plugin/). See clients/claude-code-cli/README.md.", file=sys.stderr)
    return 1


def cmd_status() -> int:
    agents = len(agent_sources())
    generated = len(list(AGENTS_OUT.glob("*.toml"))) if AGENTS_OUT.exists() else 0
    skills = len(list(SKILLS_SRC.glob("*/SKILL.md")))
    print(f"canonical agents: {agents}; Codex agent files: {generated}")
    print(f"personal assistants: {len(personal_sources())}")
    print(f"canonical skills: {skills}")
    for dest in (REPO_SKILLS_LINKS, USER_SKILLS_LINKS):
        linked = sum(1 for p in dest.iterdir() if is_link(p)) if dest.exists() else 0
        print(f"links in {dest}: {linked}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p_agents = sub.add_parser("agents")
    p_agents.add_argument("--check", action="store_true")
    p_link = sub.add_parser("link-skills")
    p_link.add_argument("--user", action="store_true")
    sub.add_parser("link-claude")
    p_personal = sub.add_parser("personal")
    p_personal.add_argument("--check", action="store_true")
    sub.add_parser("install-personal")
    sub.add_parser("status")
    args = parser.parse_args()
    if args.command == "agents":
        return cmd_agents(args.check)
    if args.command == "personal":
        return cmd_personal(args.check)
    if args.command == "install-personal":
        return cmd_install_personal()
    if args.command == "link-claude":
        return cmd_link_claude()
    if args.command == "link-skills":
        return cmd_link_skills(args.user)
    return cmd_status()


if __name__ == "__main__":
    sys.exit(main())
